def run_validate(config_path: str) -> int:
    """Validate configuration and setup."""
    logger.info({"msg": "Validating configuration", "config": config_path})

    try:
        config = load_config(config_path)
        logger.info({"msg": "Config valid", "app": config.get("app", "unknown")})

        # Check required directories
        artifacts_dir = Path("artifacts")
        if not artifacts_dir.exists():
            logger.warning({"msg": "Creating artifacts directory"})
            artifacts_dir.mkdir(parents=True, exist_ok=True)

        # Check MongoDB connection
        mongo_uri = config.get("data_layer", {}).get("mongo_buffer", {}).get("uri")
        if mongo_uri:
            logger.info({"msg": "MongoDB URI configured", "uri": mongo_uri.split("@")[-1]})
        else:
            logger.warning({"msg": "MongoDB URI not configured"})

        logger.info({"msg": "Validation complete"})
        return 0

    except Exception as e:
        logger.error({"msg": "Validation failed", "error": str(e)})
        return 1


def main() -> int:
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Trading System",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    parser.add_argument(
        "mode",
        choices=["live", "backtest", "train", "validate"],
        help="Execution mode",
    )

    parser.add_argument(
        "--config",
        "-c",
        default="configs/base.yaml",
        help="Path to config file (default: configs/base.yaml)",
    )

    parser.add_argument(
        "--symbols",
        "-s",
        nargs="+",
        default=["BTCUSDT"],
        help="Symbols to trade (default: BTCUSDT)",
    )

    parser.add_argument(
        "--start-date",
        default="2024-01-01",
        help="Backtest start date (YYYY-MM-DD)",
    )

    parser.add_argument(
        "--end-date",
        default="2024-12-31",
        help="Backtest end date (YYYY-MM-DD)",
    )

    parser.add_argument(
        "--model-type",
        default="edge",
        choices=["edge", "regime", "all"],
        help="Model type to train",
    )

    parser.add_argument(
        "--regime-model",
        default=None,
        help="Path to trained regime classifier model (.pkl)",
    )

    parser.add_argument(
        "--edge-model",
        default=None,
        help="Path to trained edge forecaster model (.pt)",
    )

    parser.add_argument(
        "--verbose",
        "-v",
        action="store_true",
        help="Enable verbose logging",
    )

    args = parser.parse_args()

    # Setup logging
    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)

    logger.info({
        "msg": "Trading system starting",
        "mode": args.mode,
        "config": args.config,
    })

    # Route to appropriate handler
    if args.mode == "live":
        return run_live(args.config, args.symbols)
    elif args.mode == "backtest":
        return run_backtest(
            args.config,
            args.start_date,
            args.end_date,
            args.symbols,
            use_real_data=True,
            regime_model_path=args.regime_model,
            edge_model_path=args.edge_model,
        )
    elif args.mode == "train":
        return run_train(args.config, args.model_type)
    elif args.mode == "validate":
        return run_validate(args.config)
    else:
        logger.error({"msg": "Unknown mode", "mode": args.mode})
        return 1


if __name__ == "__main__":
    sys.exit(main())
